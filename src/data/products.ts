export function getProduct(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

/** Currently discounted products, ordered by discount depth. */
export function getDealProducts(limit = 12): Product[] {
  return products
    .filter((product) => product.badge === "amazing")
    .slice(0, limit);
}

export function getBestSellers(limit = 12): Product[] {
  return products.filter((product) => product.isBestSeller).slice(0, limit);
}

export function getNewArrivals(limit = 12): Product[] {
  // Flagged arrivals first, then the most recently added catalogue entries so
  // the rail always has enough cards to scroll.
  const flagged = products.filter((product) => product.isNew);
  const rest = products
    .filter((product) => !product.isNew)
    .slice(-(limit - flagged.length));
  return [...flagged, ...rest].slice(0, limit);
}

/** Discounted products that are not part of the running flash sale. */
export function getSaleProducts(
  limit = 12,
  excludeIds: string[] = [],
): Product[] {
  return products
    .filter((product) => product.oldPrice && !excludeIds.includes(product.id))
    .sort(
      (a, b) =>
        (b.oldPrice! - b.price) / b.oldPrice! -
        (a.oldPrice! - a.price) / a.oldPrice!,
    )
    .slice(0, limit);
}

/** Mock personalised recommendation feed. */
export function getRecommended(limit = 12): Product[] {
  return products
    .filter((product) => product.rating >= 4.5 && product.badge !== "amazing")
    .slice(0, limit);
}

export function getMostDiscounted(limit = 10): Product[] {
  return [...products]
    .filter((product) => product.oldPrice)
    .sort(
      (a, b) =>
        (b.oldPrice! - b.price) / b.oldPrice! -
        (a.oldPrice! - a.price) / a.oldPrice!,
    )
    .slice(0, limit);
}

export function getProductsByCategory(slug: string, limit = 12): Product[] {
  return products
    .filter((product) => product.categorySlug === slug)
    .slice(0, limit);
}

/**
 * Similar products for a detail page: same subcategory first, then the rest of
 * the category, then the same brand — de-duplicated and never the product itself.
 */
export function getRelatedProducts(product: Product, limit = 8): Product[] {
  const picks: Product[] = [];
  const seen = new Set<string>([product.id]);

  const push = (candidates: Product[]) => {
    for (const candidate of candidates) {
      if (seen.has(candidate.id) || picks.length >= limit) continue;
      seen.add(candidate.id);
      picks.push(candidate);
    }
  };

  const sameCategory = products.filter(
    (item) => item.categorySlug === product.categorySlug,
  );
  const sharingSubcategory = sameCategory.filter((item) =>
    item.subcategories?.some((slug) => product.subcategories?.includes(slug)),
  );

  push(sharingSubcategory);
  push(sameCategory);
  push(products.filter((item) => item.brandSlug === product.brandSlug));
  push([...products].sort((a, b) => b.rating - a.rating));

  return picks.slice(0, limit);
}

/** Other products of the same brand, used by the brand rail on the detail page. */
export function getSameBrandProducts(product: Product, limit = 8): Product[] {
  return products
    .filter(
      (item) => item.brandSlug === product.brandSlug && item.id !== product.id,
    )
    .slice(0, limit);
}

export function getProductsByIds(ids: string[]): Product[] {
  return ids
    .map((id) => products.find((product) => product.id === id))
    .filter((product): product is Product => Boolean(product));
}
